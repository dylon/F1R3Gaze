#!/usr/bin/env python3
"""Build the chrome's monochrome icon font from the vendored Leo SVGs.

Requires fonttools (`python3 -m pip install fonttools`). Run from any directory.
The generated TTF and CSS are checked in so package builds need no Python tools.
"""

import sys
import xml.etree.ElementTree as ET
from io import BytesIO
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path


ASSETS = Path(__file__).resolve().parents[1] / "crates/gaze-shell/assets/leo"
FILES = sorted(ASSETS.glob("*.svg"))
EM = 1000
START = 0xE000


def paths(element):
    if element.tag.rsplit("}", 1)[-1] == "defs":
        return
    if element.tag.rsplit("}", 1)[-1] == "path":
        yield element.attrib["d"]
    for child in element:
        yield from paths(child)


def glyph_from(svg_file):
    svg = ET.parse(svg_file).getroot()
    assert svg.attrib["viewBox"] == "0 0 24 24", svg_file
    pen = TTGlyphPen(None)
    scaled = TransformPen(Cu2QuPen(pen, max_err=1.0), (EM / 24, 0, 0, -EM / 24, 0, EM))
    for data in paths(svg):
        parse_path(data, scaled)
    return pen.glyph()


def main():
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: build-leo-font.py [--check]")
    check = sys.argv[1:] == ["--check"]
    names = ["leo_" + file.stem.replace("-", "_") for file in FILES]
    glyph_order = [".notdef", *names]
    font = FontBuilder(EM, isTTF=True)
    font.setupGlyphOrder(glyph_order)
    font.setupCharacterMap({START + index: name for index, name in enumerate(names)})
    glyphs = {".notdef": TTGlyphPen(None).glyph(), **{
        name: glyph_from(file) for name, file in zip(names, FILES)
    }}
    font.setupGlyf(glyphs)
    # TrueType's left side bearing is the distance from the glyph origin to
    # its outline. A zero bearing moves these already-centered SVGs left.
    font.setupHorizontalMetrics({
        name: (EM, glyphs[name].xMin) for name in names
    } | {".notdef": (EM, 0)})
    font.setupHorizontalHeader(ascent=EM, descent=0)
    font.setupNameTable({
        "familyName": "F1R3Gaze Leo",
        "styleName": "Regular",
        "uniqueFontIdentifier": "F1R3Gaze Leo Regular 1.0",
        "fullName": "F1R3Gaze Leo Regular",
        "psName": "F1R3GazeLeo-Regular",
        "version": "Version 1.0",
    })
    font.setupOS2(sTypoAscender=EM, sTypoDescender=0, usWinAscent=EM, usWinDescent=0)
    font.setupPost()
    font.setupMaxp()
    font.setupHead(created=0, modified=0)
    font.font.recalcTimestamp = False
    font_bytes = BytesIO()
    font.save(font_bytes)

    css = [
        "/* Generated by scripts/build-leo-font.py from the MPL 2.0 Leo SVGs. */",
        '.leo-icon{display:inline-block;font-family:"F1R3Gaze Leo"!important;font-style:normal;font-weight:normal!important;line-height:1}',
    ]
    css.extend(
        f'.leo-{file.stem}::before{{content:"\\{START + index:04x}"}}'
        for index, file in enumerate(FILES)
    )
    generated = {
        ASSETS / "leo-icons.ttf": font_bytes.getvalue(),
        ASSETS / "leo-icons.css": ("\n".join(css) + "\n").encode(),
    }
    for path, data in generated.items():
        if check:
            if path.read_bytes() != data:
                raise SystemExit(f"{path} differs from the generated asset")
        else:
            path.write_bytes(data)


if __name__ == "__main__":
    main()
